/*
  В функцию rangeSum() приходят два целых неотрицательных числа.
  Используя цикл for, просуммируйте все четные числа в диапазоне между этими значениями (включительно)
  и верните итоговый результат.
*/
export function rangeSum(start, end) {
    // На случай, если числа пришли в обратном порядке (например, start > end),
    // определяем минимальное и максимальное значения.
    const min = Math.min(start, end);
    const max = Math.max(start, end);

    let sum = 0;

    // Идём по диапазону включительно
    for (let i = min; i <= max; i++) {
        // Проверяем, что число чётное (остаток от деления на 2 равен 0)
        if (i % 2 === 0) {
            sum += i;
        }
    }

    return sum;
}

/*
  В функцию iterationCount() приходит неотрицательное число.
  Используя цикл while, выполняйте деление этого числа на два до тех пор, пока результат деления больше 0.1
  и верните количество потребовавшихся итераций (т.е. сколько раз пришлось выполнить деление).
*/
export function iterationCount(a) {
    let count = 0;
    let current = a;

    // Делим до тех пор, пока текущее значение больше 0.1
    while (current > 0.1) {
        current = current / 2;
        count++;
    }

    return count;
}

/*
  В функцию symbolsReplace() приходит строка текста.
  Используя цикл do while, замените в тексте каждый третий символ на символ нижнего подчеркивания
  и верните итоговый результат.
*/
export function symbolsReplace(message) {
    // Разбиваем строку на массив символов, чтобы удобно менять элементы по индексу
    const chars = message.split('');
    let index = 0;

    // Проверяем, есть ли вообще символы в строке.
    // do...while должен выполниться хотя бы раз, но для пустой строки менять нечего.
    if (chars.length > 0) {
        do {
            // Каждый третий символ: индексы 2, 5, 8 и т.д.
            // (так как индексация начинается с 0: 0, 1, 2 -> 2 - это третий символ)
            if ((index + 1) % 3 === 0) {
                chars[index] = '_';
            }
            index++;
        } while (index < chars.length);
    }

    // Собираем массив обратно в строку
    return chars.join('');
}
